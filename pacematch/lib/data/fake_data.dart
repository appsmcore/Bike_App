DateTime _thisWeekend(int weekday, {int hour = 8}) {
  final now = DateTime.now();
  final daysUntil = (weekday - now.weekday + 7) % 7;
  final day = DateTime(now.year, now.month, now.day)
      .add(Duration(days: daysUntil == 0 ? 7 : daysUntil));
  return DateTime(day.year, day.month, day.day, hour, 0);
}

DateTime _inDays(int days, {int hour = 9}) {
  final now = DateTime.now().add(Duration(days: days));
  return DateTime(now.year, now.month, now.day, hour, 0);
}

DateTime _daysAgo(int days, {int hour = 8}) {
  final then = DateTime.now().subtract(Duration(days: days));
  return DateTime(then.year, then.month, then.day, hour, 0);
}

/// Demo route as flat [lat, lng, ...] around a start — for list map covers.
List<double> _demoRoute(
  double lat,
  double lng, {
  required List<(double dLat, double dLng)> deltas,
}) {
  final out = <double>[lat, lng];
  for (final d in deltas) {
    out.add(lat + d.$1);
    out.add(lng + d.$2);
  }
  return out;
}

